// IsReservedSlug reports whether the provided slug is reserved for system routes or keywords.
func IsReservedSlug(slug string) bool {
	normalized := strings.ToLower(strings.TrimSpace(slug))
	_, found := reservedSlugs[normalized]
	return found
}
